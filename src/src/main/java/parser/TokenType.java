package parser;

/** Категории токенов, распознаваемых лексическим анализатором SQL-подобного языка. */
public enum TokenType {
    /** Слово: ключевое слово или идентификатор. */
    WORD,
    /** Число: значение лежит в токене как Long или Double. */
    NUMBER,
    /** Строка в одинарных кавычках: значение без кавычек. */
    STRING,
    /** Знаки пунктуации и операторы сравнения, включая {@code <=}, {@code >=} и {@code <>}. */
    SYMBOL,
    /** Конец запроса. */
    END
}
